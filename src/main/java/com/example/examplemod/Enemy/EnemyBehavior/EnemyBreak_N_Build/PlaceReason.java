package com.example.examplemod.Enemy.EnemyBehavior.EnemyBreak_N_Build;

/**
 * НАВІЩО моб ставить блок. Кожен виклик {@link EnemyBreak_N_BuildUtils#placeBlock} мусить назвати причину:
 * <ul>
 *   <li>у лозі (категорія BUILD) видно, ЩО саме поставило кожен блок і чому гейт відмовив;</li>
 *   <li>центральний гейт ({@link EnemyBreak_N_BuildUtils#placementVeto}) може відмовити залежно від контексту
 *       (наприклад, під час паркур-стрибка нічого, крім клатча, ставити не можна).</li>
 * </ul>
 * Раніше {@code placeBlock(level, pos, mob)} не знав, хто й навіщо його кличе, тому ніщо не заважало будівельнику
 * підкласти блок під моба посеред стрибка паркуру.
 */
public enum PlaceReason {
    /**
     * Міст: блок під наступний горизонтальний крок до цілі.
     */
    BRIDGE_STEP,
    /** Міст: моб уже зійшов центром за край опори - спершу опора під самим мобом. */
    BRIDGE_UNDER_MOB,
    /** Піларинг (підйом вежею): підлога під ногами у польоті стрибка підйому. */
    PILLAR_FLOOR,
    /** Моб щойно зійшов з краю будівельного мосту і падає - блок, щоб не впасти (аварійна підлога). */
    EDGE_CATCH,
    /** Вежа: підлога/стіна/хрест-підпора. */
    TOWER_STRUCTURE,
    /** Перекриття лави над проломом / гравецького хазарду. */
    HAZARD_COVER,
    /** Клатч після нокбеку ({@link MobClutchRecovery}). */
    CLUTCH
}
